#!/bin/bash
# ============================================================
# Surface Pro 8 + WD SN740 NVMe — Ubuntu Suspend Fix
# One-click automated installer
# ============================================================
# Usage: sudo bash install.sh
# Tested on: Ubuntu 22.04+ with linux-surface kernel
# ============================================================
set -euo pipefail

# ── Color helpers ──────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
info()  { echo -e "${GREEN}[✓]${NC} $*"; }
warn()  { echo -e "${YELLOW}[!]${NC} $*"; }
error() { echo -e "${RED}[✗]${NC} $*"; }

# ── Root check ─────────────────────────────────────────────
if [[ $EUID -ne 0 ]]; then
    error "루트 권한이 필요합니다.  sudo bash $0"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "============================================"
echo " Surface Pro 8 + SN740 — Ubuntu Suspend Fix"
echo "============================================"
echo ""

# ── Auto-detect NVMe PCI address ───────────────────────────
NVME_PCI=""
for dev in /sys/bus/pci/devices/*/; do
    vendor=$(cat "$dev/vendor" 2>/dev/null) || continue
    device=$(cat "$dev/device" 2>/dev/null) || continue
    if [[ "$vendor" == "0x15b7" && "$device" == "0x5015" ]]; then
        NVME_PCI=$(basename "$dev")
        break
    fi
done

if [[ -z "$NVME_PCI" ]]; then
    # Fallback: find any NVMe controller
    for dev in /sys/bus/pci/devices/*/; do
        class=$(cat "$dev/class" 2>/dev/null) || continue
        if [[ "$class" == "0x010802" ]]; then   # NVMe class
            NVME_PCI=$(basename "$dev")
            warn "SN740 (15b7:5015) 미감지. NVMe 컨트롤러 $NVME_PCI 사용"
            break
        fi
    done
fi

if [[ -z "$NVME_PCI" ]]; then
    error "NVMe 컨트롤러를 찾을 수 없습니다."
    exit 1
fi
info "NVMe PCI 주소: $NVME_PCI"

# ──────────────────────────────────────────────────────────
# 1. GRUB 커널 파라미터 수정
# ──────────────────────────────────────────────────────────
echo ""
echo "[1/4] GRUB 커널 파라미터 수정..."
cp /etc/default/grub "/etc/default/grub.bak.$(date +%Y%m%d%H%M%S)"

CURRENT=$(grep '^GRUB_CMDLINE_LINUX_DEFAULT=' /etc/default/grub | head -1)

# Remove pcie_aspm=off (blocks S0ix entirely)
NEW_LINE=$(echo "$CURRENT" | sed 's/ *pcie_aspm=off//')

# Ensure nvme_core.default_ps_max_latency_us=0
if ! echo "$NEW_LINE" | grep -q 'nvme_core.default_ps_max_latency_us='; then
    NEW_LINE=$(echo "$NEW_LINE" | sed 's/"$/ nvme_core.default_ps_max_latency_us=0"/')
fi

# Ensure snd_hda_intel.dmic_detect=0 (Surface audio suspend fix)
if ! echo "$NEW_LINE" | grep -q 'snd_hda_intel.dmic_detect='; then
    NEW_LINE=$(echo "$NEW_LINE" | sed 's/"$/ snd_hda_intel.dmic_detect=0"/')
fi

sed -i "s|^GRUB_CMDLINE_LINUX_DEFAULT=.*|$NEW_LINE|" /etc/default/grub
update-grub 2>&1 | tail -3
info "GRUB 업데이트 완료 (pcie_aspm=off 제거, APST 비활성화)"

# ──────────────────────────────────────────────────────────
# 2. NVMe suspend/resume 훅
# ──────────────────────────────────────────────────────────
echo ""
echo "[2/4] NVMe suspend/resume 훅 생성..."

cat > /usr/lib/systemd/system-sleep/nvme-suspend.sh << HOOKEOF
#!/bin/bash
# NVMe SN740 suspend/resume hook — prevents D3cold PCIe link failure
# Auto-generated by surface-pro-sn740-fix

NVME_PCI="${NVME_PCI}"
NVME_POWER="/sys/bus/pci/devices/\$NVME_PCI/power/control"
NVME_D3COLD="/sys/bus/pci/devices/\$NVME_PCI/d3cold_allowed"

case "\$1" in
    pre)
        echo "on" > "\$NVME_POWER" 2>/dev/null
        echo 0 > "\$NVME_D3COLD" 2>/dev/null
        logger "nvme-suspend: pre-sleep — D3cold disabled"
        ;;
    post)
        echo "on" > "\$NVME_POWER" 2>/dev/null
        echo 0 > "\$NVME_D3COLD" 2>/dev/null
        logger "nvme-suspend: post-sleep — power restored"
        ;;
esac
HOOKEOF
chmod +x /usr/lib/systemd/system-sleep/nvme-suspend.sh
info "/usr/lib/systemd/system-sleep/nvme-suspend.sh 생성 완료"

# ──────────────────────────────────────────────────────────
# 3. udev 규칙
# ──────────────────────────────────────────────────────────
echo ""
echo "[3/4] NVMe udev 규칙 생성..."

VENDOR=$(cat "/sys/bus/pci/devices/$NVME_PCI/vendor" 2>/dev/null || echo "0x15b7")
DEVICE=$(cat "/sys/bus/pci/devices/$NVME_PCI/device" 2>/dev/null || echo "0x5015")

cat > /etc/udev/rules.d/60-nvme-sn740-no-d3.rules << UDEVEOF
# WD SN740 NVMe — prevent D3cold (PCIe Gen 4 link training failure)
# Vendor: ${VENDOR}, Device: ${DEVICE}
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="${VENDOR}", ATTR{device}=="${DEVICE}", ATTR{power/control}="on", ATTR{d3cold_allowed}="0"
UDEVEOF

udevadm control --reload-rules 2>/dev/null
info "/etc/udev/rules.d/60-nvme-sn740-no-d3.rules 생성 완료"

# ──────────────────────────────────────────────────────────
# 4. logind.conf
# ──────────────────────────────────────────────────────────
echo ""
echo "[4/4] logind.conf 수정 (lid 닫기 → suspend)..."
cp /etc/systemd/logind.conf "/etc/systemd/logind.conf.bak.$(date +%Y%m%d%H%M%S)"

sed -i '/^#\?HandleLidSwitch=/d'              /etc/systemd/logind.conf
sed -i '/^#\?HandleLidSwitchExternalPower=/d'  /etc/systemd/logind.conf
sed -i '/^#\?HandleLidSwitchDocked=/d'         /etc/systemd/logind.conf

sed -i '/^\[Login\]/a HandleLidSwitch=suspend\nHandleLidSwitchExternalPower=suspend\nHandleLidSwitchDocked=ignore' /etc/systemd/logind.conf
info "HandleLidSwitch=suspend 설정 완료"

# ──────────────────────────────────────────────────────────
# 즉시 적용 (재부팅 전)
# ──────────────────────────────────────────────────────────
echo ""
echo "=== 즉시 적용 ==="
echo "on" > "/sys/bus/pci/devices/$NVME_PCI/power/control" 2>/dev/null && info "NVMe power control: on"
echo 0   > "/sys/bus/pci/devices/$NVME_PCI/d3cold_allowed" 2>/dev/null && info "NVMe d3cold_allowed: 0"

echo ""
echo "============================================"
echo " 완료!"
echo ""
echo " 변경 사항:"
echo "   1. GRUB: pcie_aspm=off 제거 → S0ix 진입 허용"
echo "   2. NVMe 훅: suspend 시 D3cold 방지"
echo "   3. udev: 부팅 시 SN740 D3cold 자동 차단"
echo "   4. logind: lid 닫기 → suspend"
echo ""
echo " ⚠  재부팅 후 테스트하세요."
echo "============================================"
